from contextlib import contextmanager
import os
from django.conf import settings
from django.core.management.base import CommandError


@contextmanager
def worker_lock():
    # The OS releases this lock after a crash. Never delete a live lock file.
    with (settings.BASE_DIR / ".generation-worker.lock").open("a+b") as handle:
        if handle.tell() == 0:
            handle.write(b"0")
            handle.flush()
        handle.seek(0)
        try:
            if os.name == "nt":
                import msvcrt
                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            raise CommandError("Cannot lock the worker file. Check for another local worker or folder permission problems.") from None
        try:
            yield
        finally:
            handle.seek(0)
            if os.name == "nt":
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
